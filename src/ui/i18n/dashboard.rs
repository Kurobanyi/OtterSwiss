#[cfg(test)]
mod tests {
    use super::*;

    /// Ningún texto vacío en ningún idioma.
    #[test]
    fn textos_completos() {
        for s in [&ES, &EN] {
            for f in [
                s.active_power_plan,
                s.admin_rights_required,
                s.apply_these_optimizations,
                s.applying_system_optimizations,
                s.auto_selects_optimal_plan_for,
                s.backed_up_before_applying,
                s.backs_up_each_value_before,
                s.board,
                s.rollback_completed,
                s.rollback_incomplete,
                s.backup_deleted,
                s.backup_kept,
                s.step_applied,
                s.step_skipped,
                s.creating_backup,
                s.current_windows_scheme,
                s.detecting_hardware,
                s.disk,
                s.each_value_is_backed_up,
                s.elevate_to_modify_services_registry,
                s.included,
                s.native_win32_detection,
                s.optimize_system,
                s.optimizer,
                s.processing,
                s.reading_backup,
                s.relaunch_as_admin,
                s.restart_now,
                s.restarting_closes_every_open_app,
                s.revert_rollback,
                s.reverting_from_backup,
                s.sign_out_or_restart_to,
                s.skipped,
                s.some_changes_take_effect_after,
                s.system_overview,
            ] {
                assert!(!f.trim().is_empty());
            }
        }
    }
}
